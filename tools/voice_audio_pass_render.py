#!/usr/bin/env python3
"""Render the supplemental speech cues from stock synthetic voices.
Requires kokoro-onnx and scipy; models are local inputs, never game dependencies.
Usage: python tools/voice_audio_pass_render.py /path/to/kokoro-v1.0.onnx /path/to/voices-v1.0.bin
The manifest stores the exact spoken words separately from each display-message pattern.
"""
import hashlib, json, os, sys, wave
# Establish the kernel-enforced, fail-closed network sandbox before importing
# inference libraries. Model downloads are a separate, explicit preparation step.
os.environ['ORT_DISABLE_TELEMETRY']='1'
from voice_lesson_helpers import offline_guard
from pathlib import Path
import numpy as np
from scipy.signal import butter, sosfilt
os.environ.setdefault('OMP_NUM_THREADS','2')
from kokoro_onnx import Kokoro
import onnxruntime as ort
ort.disable_telemetry_events()
root=Path(__file__).resolve().parents[1]/'assets/voice'
manifest=json.loads((root/'audio_pass.json').read_text())
model,voices=map(Path,sys.argv[1:3])
# Limit CPU use while the C++ build runs. Kokoro accepts a pre-created session.
options=ort.SessionOptions();options.intra_op_num_threads=2;options.inter_op_num_threads=1
session=ort.InferenceSession(str(model),sess_options=options,providers=['CPUExecutionProvider'])
k=Kokoro.from_session(session,str(voices))
rows=[]
for n,row in enumerate(manifest['lines']):
 path=root/row['file']; path.parent.mkdir(exist_ok=True)
 if (not path.exists() or row.get("render_text")!=row["text"] or row.get("render_voice")!=row["voice"]
     or row.get("sha256")!=hashlib.sha256(path.read_bytes()).hexdigest()):
  samples,sr=k.create(row['text'],voice=row['voice'],speed=1.0,lang='en-gb' if row['voice'].startswith(('bf_','bm_')) else 'en-us')
  samples=sosfilt(butter(2,110,btype='highpass',fs=sr,output='sos'),samples)
  samples=sosfilt(butter(2,6800,btype='lowpass',fs=sr,output='sos'),samples)
  active=samples[np.abs(samples)>.008]; rms=np.sqrt(np.mean(active**2)) if len(active) else .1
  gain=min(.75/max(np.max(np.abs(samples)),.001),.12/max(rms,.001))
  samples*=gain
  fade=min(int(.006*sr),len(samples)//2);samples[:fade]*=np.linspace(0,1,fade);samples[-fade:]*=np.linspace(1,0,fade)
  with wave.open(str(path)+'.tmp','wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(sr);w.writeframes((np.clip(samples,-1,1)*32767).astype('<i2').tobytes())
  os.replace(str(path)+'.tmp',path)
 row['render_text']=row['text'];row['render_voice']=row['voice']
 row['sha256']=hashlib.sha256(path.read_bytes()).hexdigest()
 with wave.open(str(path),'rb') as w:row['seconds']=round(w.getnframes()/w.getframerate(),3)
 rows.append('\t'.join([row['id'],row['file'],row['text'],row['speaker'],str(row['priority']),row['kind'],row['match']]))
 print(f'{n+1}/{len(manifest["lines"])} {row["id"]}: {row["seconds"]}s',flush=True)
manifest['model_sha256']=hashlib.sha256(model.read_bytes()).hexdigest()
manifest['voices_sha256']=hashlib.sha256(voices.read_bytes()).hexdigest()
manifest['validation']={'rendered':True,'independent_asr':False,'human_listening_approved':False}
(root/'audio_pass.json').write_text(json.dumps(manifest,indent=2)+'\n')
(root/'voice_index_extra.txt').write_text('# Supplemental operational and military speech; generated by tools/voice_audio_pass_render.py\n'+'\n'.join(rows)+'\n')
